/**
 * @file Pure validation / sanitisation helpers used by both Socket.io handlers
 * and REST routes. None of these functions throw; they return normalised
 * values or `null` so callers can decide how to respond.
 */

'use strict';

const {
  MAX_LEVEL,
  MAX_SNAPSHOT_BLOCKS,
  STEM_COMPETENCIES
} = require('../config/gameConfig');

const PIN_REGEX = /^\d{4}$/;
const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const COSMETIC_REGEX = /^[a-z0-9_-]{1,40}$/i;
const MAX_NAME_LENGTH = 40;

/**
 * Check that a value is a plain (non-null, non-array) object.
 * @param {*} value
 * @returns {boolean}
 */
function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

/**
 * Normalise and validate a 4-digit room PIN. Accepts numbers (e.g. 1234) or strings.
 * Leading zeros are preserved when a string is supplied ("0420").
 * @param {*} pin
 * @returns {string|null} Normalised PIN or null when invalid.
 */
function normalizePin(pin) {
  if (typeof pin === 'number' && Number.isInteger(pin)) pin = String(pin).padStart(4, '0');
  if (typeof pin !== 'string') return null;
  const trimmed = pin.trim();
  return PIN_REGEX.test(trimmed) ? trimmed : null;
}

/**
 * Sanitise a display name (student or teacher): strips control characters and
 * angle brackets, collapses whitespace and limits length.
 * @param {*} name
 * @returns {string|null} Clean name or null when empty/invalid.
 */
function sanitizeName(name) {
  if (typeof name !== 'string') return null;
  const clean = name
    .replace(/[\u0000-\u001F\u007F<>]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, MAX_NAME_LENGTH);
  return clean.length > 0 ? clean : null;
}

/**
 * Validate a student id (UUID generated by the server).
 * @param {*} id
 * @returns {string|null}
 */
function normalizeStudentId(id) {
  if (typeof id !== 'string') return null;
  const trimmed = id.trim();
  return UUID_REGEX.test(trimmed) ? trimmed : null;
}

/**
 * Validate a level id (integer 1..MAX_LEVEL).
 * @param {*} levelId
 * @returns {number|null}
 */
function normalizeLevelId(levelId) {
  const n = typeof levelId === 'string' && levelId.trim() !== '' ? Number(levelId) : levelId;
  return Number.isInteger(n) && n >= 1 && n <= MAX_LEVEL ? n : null;
}

/**
 * Validate a strictly positive finite number with an upper bound.
 * @param {*} value
 * @param {number} max Inclusive maximum.
 * @param {{integer?: boolean}} [opts]
 * @returns {number|null}
 */
function normalizePositiveNumber(value, max, opts = {}) {
  if (typeof value !== 'number' || !Number.isFinite(value) || value <= 0 || value > max) return null;
  if (opts.integer && !Number.isInteger(value)) return null;
  return value;
}

/**
 * Validate a non-negative integer (e.g. retries count).
 * @param {*} value
 * @param {number} [max=100000]
 * @returns {number|null}
 */
function normalizeNonNegativeInt(value, max = 100000) {
  return Number.isInteger(value) && value >= 0 && value <= max ? value : null;
}

/**
 * Validate a cosmetic slug.
 * @param {*} cosmeticId
 * @returns {string|null}
 */
function normalizeCosmeticId(cosmeticId) {
  if (typeof cosmeticId !== 'string') return null;
  const trimmed = cosmeticId.trim();
  return COSMETIC_REGEX.test(trimmed) ? trimmed : null;
}

/**
 * Clamp a competency score to [0, 1]. Non-numeric input yields undefined so the
 * field is simply omitted from the stored document instead of failing validation.
 * @param {*} value
 * @returns {number|undefined}
 */
function clampScore(value) {
  const n = typeof value === 'string' && value.trim() !== '' ? Number(value) : value;
  if (typeof n !== 'number' || !Number.isFinite(n)) return undefined;
  return Math.min(1, Math.max(0, n));
}

/**
 * Validate & normalise a telemetry payload coming from the Unity client
 * (socket `student:level_completed` or POST /api/telemetry/record).
 *
 * @param {object} raw Raw telemetry object.
 * @returns {{ ok: true, value: object } | { ok: false, error: string }}
 */
function normalizeTelemetry(raw) {
  const t = isPlainObject(raw) ? raw : {};

  const retries = t.retriesCount === undefined ? 0 : normalizeNonNegativeInt(t.retriesCount);
  if (retries === null) return { ok: false, error: 'retriesCount must be a non-negative integer' };

  let timeSpent;
  if (t.timeSpentSeconds !== undefined && t.timeSpentSeconds !== null) {
    if (typeof t.timeSpentSeconds !== 'number' || !Number.isFinite(t.timeSpentSeconds) || t.timeSpentSeconds < 0) {
      return { ok: false, error: 'timeSpentSeconds must be a non-negative number' };
    }
    // Cap at 24h to avoid absurd values from a client left open overnight.
    timeSpent = Math.min(t.timeSpentSeconds, 86400);
  }

  const scoresIn = isPlainObject(t.stemCompetencyScores) ? t.stemCompetencyScores : {};
  const stemCompetencyScores = {};
  for (const { key } of STEM_COMPETENCIES) {
    const s = clampScore(scoresIn[key]);
    if (s !== undefined) stemCompetencyScores[key] = s;
  }

  let snapshot = [];
  if (t.blockProgramSnapshot !== undefined) {
    if (!Array.isArray(t.blockProgramSnapshot)) {
      return { ok: false, error: 'blockProgramSnapshot must be an array' };
    }
    if (t.blockProgramSnapshot.length > MAX_SNAPSHOT_BLOCKS) {
      return { ok: false, error: `blockProgramSnapshot exceeds ${MAX_SNAPSHOT_BLOCKS} blocks` };
    }
    snapshot = t.blockProgramSnapshot;
  }

  let completedAt = new Date();
  if (t.completedAt !== undefined) {
    const d = new Date(t.completedAt);
    if (Number.isNaN(d.getTime())) return { ok: false, error: 'completedAt must be a valid date' };
    completedAt = d;
  }

  return {
    ok: true,
    value: {
      retriesCount: retries,
      timeSpentSeconds: timeSpent,
      subroutinesUsed: t.subroutinesUsed === true,
      completedAt,
      stemCompetencyScores,
      blockProgramSnapshot: snapshot
    }
  };
}

module.exports = {
  isPlainObject,
  normalizePin,
  sanitizeName,
  normalizeStudentId,
  normalizeLevelId,
  normalizePositiveNumber,
  normalizeNonNegativeInt,
  normalizeCosmeticId,
  clampScore,
  normalizeTelemetry
};
